#!/usr/bin/env python3
"""One RGB565 palette source for the ADV screen and SwiftUI editor."""
import json,sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'Assets/themes.json').read_text())
rows=data['themes'];assert len(rows)==38
roles=['accent','alternate','surface','text','inverse','background','chrome']
def write_or_check(path,text):
    if '--check' in sys.argv:
        if not path.exists() or path.read_text()!=text:raise SystemExit('Regenerate themes: '+str(path))
    else:
        path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
for row in rows:assert all(isinstance(row[k],int) and 0<=row[k]<=65535 for k in roles)
for a,b in zip(rows[::2],rows[1::2]):
    assert a['accent']==b['alternate'] and a['alternate']==b['accent']
    assert all(a[k]==b[k] for k in roles[2:])
header=['/* Generated by Tools/generate_themes.py; palettes from GlitchDrums FM1. */','#pragma once','#include <stdint.h>','typedef struct { const char *name; uint16_t '+','.join(roles)+'; } GSTheme;','static const GSTheme gs_themes[] = {']
for row in rows:header.append('{'+json.dumps(row['name'])+','+','.join(hex(row[k]) for k in roles)+'},')
header+=['};',f'#define GS_THEME_COUNT {len(rows)}',f'#define GS_DEFAULT_THEME {data["default"]}']
write_or_check(root/'Device/ADV/src/Themes.h','\n'.join(header)+'\n')
swift=['// Generated from Assets/themes.json by Tools/generate_themes.py.','import SwiftUI','','struct SynthTheme: Identifiable, Sendable {','    let id: Int','    let name: String','    let colors: [UInt16]','    private func color(_ index: Int) -> Color {','        let raw = colors[index]','        return Color(red: Double((raw >> 11) & 31) / 31, green: Double((raw >> 5) & 63) / 63, blue: Double(raw & 31) / 31)','    }']
for i,role in enumerate(roles):swift.append(f'    var {role}: Color {{ color({i}) }}')
swift+=['    var isLight: Bool {','        let raw = colors[5]','        let r = Double((raw >> 11) & 31) / 31, g = Double((raw >> 5) & 63) / 63, b = Double(raw & 31) / 31','        return 0.2126 * r + 0.7152 * g + 0.0722 * b > 0.5','    }',f'    static let defaultIndex = {data["default"]}','    static let all: [SynthTheme] = [']
for index,row in enumerate(rows):swift.append('        SynthTheme(id: '+str(index)+', name: '+json.dumps(row['name'])+', colors: ['+', '.join(hex(row[k]) for k in roles)+']),')
swift+=['    ]','}','','extension EnvironmentValues {','    @Entry var synthTheme: SynthTheme = SynthTheme.all[SynthTheme.defaultIndex]','}']
write_or_check(root/'Apple/Shared/SynthTheme.swift','\n'.join(swift)+'\n')
